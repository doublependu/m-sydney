// tools/build-road-tags.mjs: writes js/road-tags.js, what OpenStreetMap says is painted on the roads and standing beside
// them: bus lanes, cycle lanes and cycleways, speed limits, one-way streets, zebra crossings, motorway direction signs.
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { inDetail, load, q1, rdp, toWorld } from './geo-common.mjs';

const OUT = process.argv[2] || fileURLToPath(new URL('./data/generated/road-tags.js', import.meta.url));
const ways = load('all_roads.json').elements.filter((e) => e.type === 'way' && e.geometry);
const worldOf = (w) => {
  const pts = w.geometry.map((g) => toWorld(g.lon, g.lat));
  return w.tags?.oneway === '-1' ? pts.reverse() : pts;
};
const lengthOf = (pts) => pts.reduce((sum, p, i) => (i ? sum + Math.hypot(p[0] - pts[i - 1][0], p[1] - pts[i - 1][1]) : 0), 0);
const flat = (pts) => pts.flatMap(([x, z]) => [q1(x), q1(z)]);
const pointAlong = (pts, at) => {
  let d = 0;
  for (let i = 1; i < pts.length; i++) {
    const L = Math.hypot(pts[i][0] - pts[i - 1][0], pts[i][1] - pts[i - 1][1]);
    if (d + L >= at && L > 0) {
      const t = (at - d) / L;
      return [pts[i - 1][0] + (pts[i][0] - pts[i - 1][0]) * t, pts[i - 1][1] + (pts[i][1] - pts[i - 1][1]) * t, (pts[i][0] - pts[i - 1][0]) / L, (pts[i][1] - pts[i - 1][1]) / L];
    }
    d += L;
  }
  return null;
};
const oneWay = (t) => t.oneway === 'yes' || t.oneway === '-1' || t.highway === 'motorway' || t.highway === 'motorway_link';
const isRamp = (t) => /_link$|^motorway/.test(t.highway || '');
const onSurface = (t) => !(t.tunnel && t.tunnel !== 'no');

const tags = { buses: [], cycles: [], cycleways: [], speeds: [], oneways: [], zebras: [], directions: [] };
for (const w of ways) {
  const t = w.tags || {};
  if (!onSurface(t)) continue;
  const pts = worldOf(w);
  if (!pts.some(([x, z]) => inDetail(x, z))) continue;
  const L = lengthOf(pts);
  const shape = rdp(pts, 0.5);
  const designated = (v) => typeof v === 'string' && /designated/.test(v);
  if (L > 15 && (t.busway === 'lane' || /lane/.test(t['busway:left'] || '') || t['lanes:bus'] || designated(t['bus:lanes']) || designated(t['psv:lanes']))) tags.buses.push(flat(shape));
  const lane = (v) => v === 'lane';
  if (L > 15) {
    // side: 1 the left of the way, as a one-way street's kerb lane; 2 the right; 3 both
    const left = lane(t['cycleway:left']) || lane(t['cycleway:both']) || lane(t.cycleway);
    const right = lane(t['cycleway:right']) || lane(t['cycleway:both']) || (lane(t.cycleway) && !oneWay(t));
    if (left || right) tags.cycles.push([(left ? 1 : 0) + (right ? 2 : 0), ...flat(shape)]);
  }
  const speed = Number(t.maxspeed);
  if (speed >= 10 && speed <= 110 && L > 70 && !isRamp(t)) {
    for (let at = 35; at < L - 20; at += 260) {
      const p = pointAlong(pts, at);
      if (p && inDetail(p[0], p[1])) tags.speeds.push([speed, q1(p[0]), q1(p[1]), +p[2].toFixed(3), +p[3].toFixed(3), oneWay(t) ? 1 : 0]);
    }
  }
  if (oneWay(t) && !isRamp(t) && L > 25) {
    const p = pointAlong(pts, 8);
    if (p && inDetail(p[0], p[1])) tags.oneways.push(q1(p[0]), q1(p[1]), +p[2].toFixed(3), +p[3].toFixed(3));
  }
  if (t.destination && L > 10) {
    const p = pointAlong(pts, Math.min(25, L * 0.3));
    if (p && inDetail(p[0], p[1])) tags.directions.push([t.destination.split(';').slice(0, 3).join(' · '), q1(p[0]), q1(p[1]), +p[2].toFixed(3), +p[3].toFixed(3)]);
  }
}
for (const w of load('cycleways.json').elements) {
  if (w.type !== 'way' || !w.geometry || (w.tags?.tunnel && w.tags.tunnel !== 'no')) continue;
  const pts = w.geometry.map((g) => toWorld(g.lon, g.lat));
  if (pts.some(([x, z]) => inDetail(x, z)) && lengthOf(pts) > 10) tags.cycleways.push(flat(rdp(pts, 0.5)));
}
for (const n of load('nodes.json').elements) {
  const t = n.tags || {};
  if (t.highway !== 'crossing') continue;
  const zebra = t.crossing === 'zebra' || /zebra/.test(t['crossing:markings'] || '');
  if (!zebra || t.crossing === 'traffic_signals') continue;
  const [x, z] = toWorld(n.lon, n.lat);
  if (inDetail(x, z)) tags.zebras.push(q1(x), q1(z));
}
fs.writeFileSync(OUT, `// Generated by tools/build-road-tags.mjs; do not edit. © OpenStreetMap contributors, ODbL.
export const ROAD_TAGS = ${JSON.stringify(tags)};
`);
console.log('[road-tags]', Object.entries(tags).map(([k, v]) => `${k} ${v.length}`).join(', '), (fs.statSync(OUT).size / 1024).toFixed(0), 'KB');
