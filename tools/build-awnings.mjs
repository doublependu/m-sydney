// tools/build-awnings.mjs: writes js/awning-geodata.js from the City of Sydney's plan of its street awnings.
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import { inDetail, load, q1, rdp, toWorld } from './geo-common.mjs';

const OUT = process.argv[2] || fileURLToPath(new URL('./data/generated/awning-geodata.js', import.meta.url));
const KIND = { 'Continuous awning': 0, 'Awning over entries': 1, Colonnades: 2 };
const lines = [];
for (const f of load('cos_awnings.json')) {
  const kind = KIND[f.properties.AwningType];
  if (kind === undefined || !f.geometry) continue;
  for (const line of f.geometry.type === 'LineString' ? [f.geometry.coordinates] : f.geometry.coordinates) {
    const pts = rdp(line.map(([lon, lat]) => toWorld(lon, lat)), 0.4);
    if (pts.length < 2 || !pts.some(([x, z]) => inDetail(x, z))) continue;
    lines.push([kind, ...pts.flatMap(([x, z]) => [q1(x), q1(z)])]);
  }
}
fs.writeFileSync(OUT, `// Generated by tools/build-awnings.mjs; do not edit.
// City of Sydney Development Control Plan 2012, CC BY 4.0. Each line: kind (0 continuous, 1 over entries, 2 colonnade), then x, z, ...
export const AWNINGS = ${JSON.stringify(lines)};
`);
console.log('[awnings]', lines.length, 'lines,', (fs.statSync(OUT).size / 1024).toFixed(0), 'KB');
